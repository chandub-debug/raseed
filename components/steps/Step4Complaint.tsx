"use client";

import { useState, useEffect } from "react";
import {
  AlertTriangle, ArrowLeft, Download, Copy, Check,
  ExternalLink, FileText, ListChecks, Navigation,
  RefreshCw, CheckCircle2,
} from "lucide-react";
import { cn } from "@/lib/utils";
import LoadingSpinner from "@/components/ui/LoadingSpinner";
import DisclaimerBanner from "@/components/ui/DisclaimerBanner";
import type { DisputeSession, ComplaintDraft } from "@/lib/types";

interface Step4ComplaintProps {
  session: DisputeSession;
  onUpdate: (updates: Partial<DisputeSession>) => void;
  onBack: () => void;
  onStartOver: () => void;
}

export default function Step4Complaint({
  session, onUpdate, onBack, onStartOver,
}: Step4ComplaintProps) {
  const [isLoading, setIsLoading]   = useState(false);
  const [error, setError]           = useState<string | null>(null);
  const [complaint, setComplaint]   = useState<ComplaintDraft | null>(session.complaint);
  const [copied, setCopied]         = useState(false);
  const [confirmed, setConfirmed]   = useState(false);

  // Auto-generate on mount if no complaint yet
  useEffect(() => {
    if (!complaint) {
      generateComplaint();
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  async function generateComplaint() {
    if (!session.analysis) {
      setError("Case analysis is missing. Please go back and complete Step 3.");
      return;
    }
    setIsLoading(true);
    setError(null);
    setConfirmed(false);

    try {
      const res = await fetch("/api/generate-complaint", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          facts: session.facts,
          evidenceClaims: session.analysis.evidenceClaims,
          analysis: session.analysis,
        }),
      });
      const data = await res.json() as { complaint?: ComplaintDraft; error?: string };
      if (data.error) throw new Error(data.error);
      if (!data.complaint) throw new Error("No complaint returned from server.");

      setComplaint(data.complaint);
      onUpdate({ complaint: data.complaint });
    } catch (err) {
      setError(err instanceof Error ? err.message : "Failed to generate complaint. Please try again.");
    } finally {
      setIsLoading(false);
    }
  }

  async function copyToClipboard() {
    if (!complaint) return;
    const text = buildPlainText(complaint);
    await navigator.clipboard.writeText(text);
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  }

  function downloadComplaint() {
    if (!complaint) return;
    const text = buildPlainText(complaint);
    const blob = new Blob([text], { type: "text/plain;charset=utf-8" });
    const url  = URL.createObjectURL(blob);
    const a    = document.createElement("a");
    a.href     = url;
    a.download = "RASEED_Complaint.txt";
    a.click();
    URL.revokeObjectURL(url);
  }

  function buildPlainText(c: ComplaintDraft): string {
    const lines: string[] = [];
    lines.push(`To: ${c.to}`);
    lines.push(`Subject: ${c.subject}`);
    lines.push("");
    lines.push(c.body);
    lines.push("");
    lines.push("Relief Sought:");
    c.reliefSought.forEach((r, i) => lines.push(`  ${i + 1}. ${r}`));
    lines.push("");
    lines.push("Enclosures:");
    c.enclosures.forEach((e, i) => lines.push(`  ${i + 1}. ${e}`));
    lines.push("");
    lines.push("---");
    lines.push("Generated by RASEED — Consumer Dispute Assistant");
    lines.push("Please review before sending. RASEED is not a substitute for legal advice.");
    return lines.join("\n");
  }

  // ── Loading ──────────────────────────────────────────────────────────────────
  if (isLoading) {
    return (
      <div className="flex flex-col items-center justify-center h-full gap-4 p-8">
        <LoadingSpinner size="lg" label="Drafting your complaint…" />
        <p className="text-sm text-surface-400 text-center max-w-xs">
          Writing a formal complaint based on your verified facts and legal grounds.
        </p>
      </div>
    );
  }

  // ── Error ────────────────────────────────────────────────────────────────────
  if (error) {
    return (
      <div className="flex flex-col items-center justify-center h-full gap-4 p-8">
        <AlertTriangle className="w-10 h-10 text-red-400" />
        <p className="text-surface-700 font-medium text-center">{error}</p>
        <div className="flex gap-3">
          <button onClick={onBack} className="btn-secondary">
            <ArrowLeft className="w-4 h-4" /> Back
          </button>
          <button onClick={generateComplaint} className="btn-primary">
            Try again
          </button>
        </div>
      </div>
    );
  }

  if (!complaint) return null;

  return (
    <div className="flex flex-col gap-5 p-5 overflow-y-auto">

      {/* ── Review reminder ─────────────────────────────────────────────────── */}
      <DisclaimerBanner />

      {/* ── Complaint letter ─────────────────────────────────────────────────── */}
      <section className="card overflow-hidden">
        {/* Header */}
        <div className="flex items-center justify-between px-5 py-4 bg-surface-50 border-b border-surface-200">
          <div className="flex items-center gap-2">
            <FileText className="w-4 h-4 text-brand-500" />
            <h2 className="text-sm font-semibold text-surface-800">Complaint Letter</h2>
          </div>
          <div className="flex gap-2">
            <button
              onClick={copyToClipboard}
              className="btn-secondary text-xs px-3 py-1.5 h-auto"
              aria-label="Copy to clipboard"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-green-500" /> : <Copy className="w-3.5 h-3.5" />}
              {copied ? "Copied!" : "Copy"}
            </button>
            <button
              onClick={downloadComplaint}
              className="btn-secondary text-xs px-3 py-1.5 h-auto"
              aria-label="Download as text file"
            >
              <Download className="w-3.5 h-3.5" />
              Download
            </button>
          </div>
        </div>

        {/* Letter content */}
        <div className="p-5 space-y-3 bg-white">
          <div className="space-y-1">
            <p className="text-xs text-surface-400 font-medium uppercase tracking-wide">To</p>
            <p className="text-sm font-semibold text-surface-800">{complaint.to}</p>
          </div>
          <div className="space-y-1">
            <p className="text-xs text-surface-400 font-medium uppercase tracking-wide">Subject</p>
            <p className="text-sm font-semibold text-surface-800">{complaint.subject}</p>
          </div>
          <hr className="border-surface-100" />
          <div className="text-sm text-surface-800 leading-relaxed whitespace-pre-wrap font-mono bg-surface-50 rounded-xl p-4 border border-surface-100">
            {complaint.body}
          </div>
        </div>
      </section>

      {/* ── Relief sought ──────────────────────────────────────────────────────── */}
      <section className="card p-4 space-y-3">
        <h2 className="text-sm font-semibold text-surface-800 flex items-center gap-2">
          <ListChecks className="w-4 h-4 text-brand-500" />
          Relief Sought
        </h2>
        <ol className="space-y-2">
          {complaint.reliefSought.map((item, i) => (
            <li key={i} className="flex items-start gap-3 text-sm text-surface-700">
              <span className="w-5 h-5 rounded-full bg-brand-100 text-brand-600 text-xs font-bold flex items-center justify-center flex-shrink-0 mt-0.5">
                {i + 1}
              </span>
              {item}
            </li>
          ))}
        </ol>
      </section>

      {/* ── Enclosures ─────────────────────────────────────────────────────────── */}
      {complaint.enclosures.length > 0 && (
        <section className="card p-4 space-y-3">
          <h2 className="text-sm font-semibold text-surface-800 flex items-center gap-2">
            <FileText className="w-4 h-4 text-brand-500" />
            Documents to Attach
          </h2>
          <ul className="space-y-1.5">
            {complaint.enclosures.map((enc, i) => (
              <li key={i} className="flex items-center gap-2 text-sm text-surface-700">
                <span className="w-1.5 h-1.5 rounded-full bg-brand-400 flex-shrink-0" />
                {enc}
              </li>
            ))}
          </ul>
        </section>
      )}

      {/* ── Next steps ─────────────────────────────────────────────────────────── */}
      {complaint.nextSteps.length > 0 && (
        <section className="card p-4 space-y-3">
          <h2 className="text-sm font-semibold text-surface-800 flex items-center gap-2">
            <Navigation className="w-4 h-4 text-brand-500" />
            Your Next Steps
          </h2>
          <ol className="space-y-4">
            {complaint.nextSteps.map((step) => (
              <li key={step.order} className="flex gap-4">
                <div className="w-7 h-7 rounded-full bg-brand-500 text-white text-xs font-bold flex items-center justify-center flex-shrink-0 mt-0.5">
                  {step.order}
                </div>
                <div className="flex-1 space-y-1">
                  <p className="text-sm font-medium text-surface-800">{step.action}</p>
                  <p className="text-xs text-surface-500">{step.notes}</p>
                  <div className="flex items-center gap-2">
                    <span className="text-xs bg-surface-100 text-surface-600 px-2 py-0.5 rounded-full">
                      {step.channel}
                    </span>
                    {step.url && (
                      <a
                        href={step.url}
                        target="_blank"
                        rel="noopener noreferrer"
                        className="inline-flex items-center gap-1 text-xs text-brand-600 hover:text-brand-700"
                      >
                        Visit portal
                        <ExternalLink className="w-3 h-3" />
                      </a>
                    )}
                  </div>
                </div>
              </li>
            ))}
          </ol>
        </section>
      )}

      {/* ── Confirmation checkbox ──────────────────────────────────────────────── */}
      <label className="flex items-start gap-3 bg-surface-50 border border-surface-200 rounded-xl px-4 py-3 cursor-pointer group">
        <input
          type="checkbox"
          checked={confirmed}
          onChange={(e) => setConfirmed(e.target.checked)}
          className="mt-0.5 w-4 h-4 accent-brand-500 cursor-pointer"
          aria-label="I have reviewed this complaint"
        />
        <span className="text-sm text-surface-700 group-hover:text-surface-900 transition-colors">
          I have read and reviewed this complaint. I understand that RASEED has
          generated this draft and I am responsible for verifying its accuracy before
          sending it.
        </span>
      </label>

      {/* ── Action buttons ────────────────────────────────────────────────────── */}
      <div
        className={cn(
          "card p-4 space-y-3 transition-all duration-300",
          confirmed ? "border-green-200 bg-green-50" : "opacity-60 pointer-events-none"
        )}
      >
        <p className="text-sm font-semibold text-surface-800 flex items-center gap-2">
          <CheckCircle2 className={cn("w-4 h-4", confirmed ? "text-green-500" : "text-surface-300")} />
          Ready to use
        </p>
        <div className="flex flex-wrap gap-3">
          <button onClick={copyToClipboard} className="btn-primary">
            {copied ? <Check className="w-4 h-4" /> : <Copy className="w-4 h-4" />}
            {copied ? "Copied!" : "Copy Complaint"}
          </button>
          <button onClick={downloadComplaint} className="btn-secondary">
            <Download className="w-4 h-4" />
            Download .txt
          </button>
        </div>
      </div>

      {/* ── Bottom navigation ─────────────────────────────────────────────────── */}
      <div className="flex justify-between pt-2 pb-4">
        <button onClick={onBack} className="btn-secondary">
          <ArrowLeft className="w-4 h-4" />
          Back
        </button>
        <button
          onClick={generateComplaint}
          className="btn-secondary text-sm"
        >
          <RefreshCw className="w-3.5 h-3.5" />
          Regenerate
        </button>
        <button
          onClick={onStartOver}
          className="text-sm text-surface-400 hover:text-surface-600 underline transition-colors"
        >
          Start a new case
        </button>
      </div>
    </div>
  );
}
